// Generates src/engine/facemesh-data.ts from MediaPipe's canonical face model.
// Landmark i in FaceLandmarker output == vertex i in canonical_face_model.obj.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const obj = await readFile(resolve(root, 'scripts/data/canonical_face_model.obj'), 'utf8');

const pos = [];
const vt = [];
const tris = [];
const uvOfVertex = new Map();

for (const line of obj.split('\n')) {
  const p = line.trim().split(/\s+/);
  if (p[0] === 'v') pos.push(p.slice(1, 4).map(Number));
  else if (p[0] === 'vt') vt.push(p.slice(1, 3).map(Number));
  else if (p[0] === 'f') {
    const tri = p.slice(1, 4).map((s) => {
      const [vi, ti] = s.split('/').map((n) => Number(n) - 1);
      const prev = uvOfVertex.get(vi);
      if (prev !== undefined && prev !== ti) {
        const a = vt[prev], b = vt[ti];
        if (Math.hypot(a[0] - b[0], a[1] - b[1]) > 1e-6) throw new Error(`vertex ${vi} has multiple UVs`);
      }
      uvOfVertex.set(vi, ti);
      return vi;
    });
    tris.push(tri);
  }
}

const N = pos.length;
// OBJ UV has v pointing up; flip so v=0 is the top of the forehead (texture space).
const uvs = new Float32Array(N * 2);
for (let i = 0; i < N; i++) {
  const t = vt[uvOfVertex.get(i)];
  uvs[i * 2] = t[0];
  uvs[i * 2 + 1] = 1 - t[1];
}

// Boundary edges = edges used by exactly one triangle.
const edgeCount = new Map();
const key = (a, b) => (a < b ? `${a},${b}` : `${b},${a}`);
for (const [a, b, c] of tris) for (const [x, y] of [[a, b], [b, c], [c, a]]) edgeCount.set(key(x, y), (edgeCount.get(key(x, y)) ?? 0) + 1);
const adj = new Map();
for (const [k, n] of edgeCount) {
  if (n !== 1) continue;
  const [a, b] = k.split(',').map(Number);
  if (!adj.has(a)) adj.set(a, []);
  if (!adj.has(b)) adj.set(b, []);
  adj.get(a).push(b);
  adj.get(b).push(a);
}

// Walk boundary loops.
const seen = new Set();
const loops = [];
for (const start of adj.keys()) {
  if (seen.has(start)) continue;
  const loop = [start];
  seen.add(start);
  let prev = -1, cur = start;
  for (;;) {
    const next = adj.get(cur).find((n) => n !== prev && !seen.has(n));
    if (next === undefined) break;
    loop.push(next);
    seen.add(next);
    prev = cur;
    cur = next;
  }
  loops.push(loop);
}
loops.sort((a, b) => b.length - a.length);
const outer = loops[0];
if (loops.length !== 1) throw new Error(`expected 1 boundary loop, got ${loops.length}`);

// Eye openings and inner lips are covered by triangles in the canonical mesh,
// so their contours come from MediaPipe's standard connection sets instead.
const RIGHT_EYE = [33, 7, 163, 144, 145, 153, 154, 155, 133, 173, 157, 158, 159, 160, 161, 246];
const LEFT_EYE = [263, 249, 390, 373, 374, 380, 381, 382, 362, 398, 384, 385, 386, 387, 388, 466];
const MOUTH_INNER = [78, 95, 88, 178, 87, 14, 317, 402, 318, 324, 308, 415, 310, 311, 312, 13, 82, 81, 80, 191];

// Ring distance from the outer boundary -> feather weight.
const neighbors = Array.from({ length: N }, () => new Set());
for (const [a, b, c] of tris) {
  neighbors[a].add(b).add(c);
  neighbors[b].add(a).add(c);
  neighbors[c].add(a).add(b);
}
const ring = new Int32Array(N).fill(-1);
let frontier = [...outer];
for (const i of frontier) ring[i] = 0;
for (let d = 1; frontier.length; d++) {
  const next = [];
  for (const i of frontier) for (const n of neighbors[i]) if (ring[n] < 0) { ring[n] = d; next.push(n); }
  frontier = next;
}
const feather = Array.from(ring, (r) => Math.min(1, (r + 1) / 4));

// Skirt: a ring of extra vertices pushed outward from the face oval so paint reaches the
// hairline and fades out softly instead of stopping at the mesh edge. Push hardest at the
// forehead, barely at the jaw (so the neck and background stay clean).
const ovalUvCenter = outer.reduce((a, i) => [a[0] + uvs[i * 2] / outer.length, a[1] + uvs[i * 2 + 1] / outer.length], [0, 0]);
const smooth = (e0, e1, x) => { const t = Math.min(1, Math.max(0, (x - e0) / (e1 - e0))); return t * t * (3 - 2 * t); };
const extend = outer.map((i) => +(0.05 + 0.3 * smooth(0.6, 0.15, uvs[i * 2 + 1])).toFixed(3));
const skirtUvs = outer.flatMap((i, k) => [0, 1].map((c) => uvs[i * 2 + c] + (uvs[i * 2 + c] - ovalUvCenter[c]) * extend[k]));
const skirtTris = [];
for (let k = 0; k < outer.length; k++) {
  const k2 = (k + 1) % outer.length;
  const a = outer[k], b = outer[k2], ea = N + k, eb = N + k2;
  skirtTris.push([a, b, eb], [a, eb, ea]);
}
const allTris = [...tris, ...skirtTris];
const allUvs = [...uvs, ...skirtUvs];
const allFeather = [...feather, ...outer.map(() => 0)];

const fmt = (arr, digits) => Array.from(arr, (v) => (digits === undefined ? v : +v.toFixed(digits))).join(',');
const out = `// AUTO-GENERATED by scripts/gen-facemesh.mjs — do not edit.
// Topology + UVs of MediaPipe's canonical face model (Apache-2.0).

/** Landmark vertices; skirt vertices follow at indices FACE_VERTEX_COUNT + k for FACE_OVAL[k]. */
export const FACE_VERTEX_COUNT = ${N};
export const FACE_TOTAL_VERTICES = ${N + outer.length};
export const FACE_TRIANGLES = new Uint16Array([${fmt(allTris.flat())}]);
/** Per-vertex UV, v=0 at the top of the forehead (skirt UVs extrapolate past the mesh). */
export const FACE_UVS = new Float32Array([${fmt(allUvs, 5)}]);
/** 0 on the skirt's outer edge, ramping to 1 a few rings inside the face. */
export const FACE_FEATHER = new Float32Array([${fmt(allFeather, 3)}]);
export const FACE_OVAL = [${outer.join(',')}];
/** How far each skirt vertex sits beyond its oval vertex, as a fraction of the distance from the oval's center. */
export const FACE_SKIRT = new Float32Array([${extend.join(',')}]);
export const MOUTH_INNER = [${MOUTH_INNER}];
/** Subject's right eye (appears on the left of an unmirrored image). */
export const RIGHT_EYE = [${RIGHT_EYE}];
export const LEFT_EYE = [${LEFT_EYE}];
export const RIGHT_IRIS = 468;
export const LEFT_IRIS = 473;
`;
await writeFile(resolve(root, 'src/engine/facemesh-data.ts'), out);
console.log(`faces=${tris.length} verts=${N} outer=${outer.length}`);
const uv = (i) => `(${uvs[i * 2].toFixed(3)},${uvs[i * 2 + 1].toFixed(3)})`;
console.log(`uv 10(forehead)=${uv(10)} 152(chin)=${uv(152)} 33(R eye outer)=${uv(33)} 263(L eye outer)=${uv(263)} 1(nose tip)=${uv(1)} 13(upper lip)=${uv(13)}`);
console.log('missing uv:', N - uvOfVertex.size);
