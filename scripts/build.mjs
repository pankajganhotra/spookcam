// Builds the unpacked extension into dist/. `node scripts/build.mjs --watch` rebuilds on change.
import * as esbuild from 'esbuild';
import { cp, mkdir, readFile, rm, writeFile, access } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(root, 'dist');
const watch = process.argv.includes('--watch');
const dev = watch || process.argv.includes('--dev');

const exists = (p) => access(p).then(() => true, () => false);

// MediaPipe's Emscripten loader declares a global `ModuleFactory`. Wrap it in a module scope so
// it neither leaks into nor collides with the host page (Meet ships its own MediaPipe).
async function generateLoader() {
  const src = await readFile(resolve(root, 'node_modules/@mediapipe/tasks-vision/wasm/vision_wasm_internal.js'), 'utf8');
  const body = src.replace(/\/\/ Export using a UMD style export[\s\S]*$/, '');
  if (body === src) throw new Error('MediaPipe loader layout changed: UMD footer not found');
  const out = `// AUTO-GENERATED by scripts/build.mjs from @mediapipe/tasks-vision (Apache-2.0).\n/* eslint-disable */\nexport const ModuleFactory = (() => {\n${body}\nreturn ModuleFactory;\n})();\n`;
  await mkdir(resolve(root, 'src/engine/vendor'), { recursive: true });
  await writeFile(resolve(root, 'src/engine/vendor/mediapipe-loader.js'), out);
}

async function copyStatic() {
  await mkdir(resolve(dist, 'wasm'), { recursive: true });
  await cp(resolve(root, 'node_modules/@mediapipe/tasks-vision/wasm/vision_wasm_internal.wasm'), resolve(dist, 'wasm/vision.wasm'));
  await cp(resolve(root, 'public'), dist, { recursive: true });
  await cp(resolve(root, 'manifest.json'), resolve(dist, 'manifest.json'));
  for (const page of ['popup', 'studio', 'detector', 'reload']) {
    await cp(resolve(root, `src/${page}/${page}.html`), resolve(dist, `${page}.html`));
  }
  for (const m of ['face_landmarker.task', 'selfie_segmenter.tflite', 'hand_landmarker.task']) {
    if (!(await exists(resolve(dist, 'models', m)))) throw new Error(`missing public/models/${m} — run \`npm run fetch-assets\``);
  }
}

const common = {
  bundle: true,
  target: 'chrome116',
  minify: !dev,
  sourcemap: dev ? 'inline' : false,
  legalComments: 'none',
  // The Emscripten loader has Node-only branches (`import('node:fs')`) that never run in Chrome.
  external: ['node:*'],
  logLevel: 'info',
  define: { 'process.env.NODE_ENV': dev ? '"development"' : '"production"' },
};

const builds = [
  { entryPoints: { hook: 'src/content/hook.ts', bridge: 'src/content/bridge.ts', engine: 'src/engine/main.ts' }, format: 'iife' },
  { entryPoints: { background: 'src/background.ts' }, format: 'esm' },
  { entryPoints: { popup: 'src/popup/popup.ts', studio: 'src/studio/studio.ts', detector: 'src/detector/detector.ts', reload: 'src/reload/reload.ts' }, format: 'esm', loader: { '.css': 'css' } },
];

await rm(dist, { recursive: true, force: true });
await generateLoader();
await copyStatic();

const ctxs = await Promise.all(
  builds.map((b) => esbuild.context({ ...common, ...b, absWorkingDir: root, outdir: dist })),
);
if (watch) {
  await Promise.all(ctxs.map((c) => c.watch()));
  console.log('watching… (static files are copied once; restart to pick up html/manifest changes)');
} else {
  await Promise.all(ctxs.map((c) => c.rebuild()));
  await Promise.all(ctxs.map((c) => c.dispose()));
  console.log(`built → ${dist}`);
}
